'use strict';
const assert = require('node:assert/strict');
const M = require('../src/core/mltt.js');
const { levels } = require('../src/levels/index.js');
const b = (type, inputs = {}, fields = {}, id = type) => ({ type, inputs, fields, id });
const nat = b('tt_nat'), zero = b('tt_zero'), bool = b('tt_bool');
const judgment = (term, type) => b('tt_judgment', { TERM: term, TYPE: type });
const problem = term => b('tt_problem', { TERM: term });
const custom = (term, declarations = []) => M.checkCustomProblem(problem(term), declarations);
assert(custom(zero).ok, 'A raw term can occupy the entry');
assert(custom(judgment(zero, nat)).ok);
assert(!custom(judgment(zero, bool)).ok, 'A forged judgment type fails');
assert(!custom(judgment(zero)).ok, 'A missing type is a genuine hole');
assert(!custom(judgment(null, nat)).ok, 'A missing term is a genuine hole');
assert(!custom(b('tt_annot', { TERM: b('tt_hole'), TYPE: nat })).ok, 'Explicit holes cannot disappear inside annotations');
const arrow = b('tt_pi', { DOM: nat, BODY: nat });
arrow.binds = { BODY: ['pi-x'] }; arrow.names = { 'pi-x': 'x' };
const h = b('tt_declare', { TYPE: arrow }, { KIND: 'axiom', NAME: 'h' }, 'h');
const refH = b('tt_symbol', {}, { REF: 'h' });
const app = (f, a) => b('tt_app', { F: f, A: a });
const rule = (f, a, result) => b('tt_rule_app', { F: f, A: a, RULE: b('tt_rule_pi_elim'), RESULT: result });
const result = app(refH, zero);
assert(custom(rule(refH, zero, result), [h]).ok);
assert(custom(rule(judgment(refH, arrow), judgment(zero, nat), judgment(result, nat)), [h]).ok);
assert(!custom(rule(refH, zero, zero), [h]).ok, 'A same-typed but different conclusion fails');
assert(!custom(rule(refH, zero, judgment(result, bool)), [h]).ok, 'A forged conclusion type fails');
assert(!custom(rule(refH, zero), [h]).ok, 'An empty conclusion fails');
const noRule = rule(refH, zero, result); delete noRule.inputs.RULE;
assert.equal(custom(noRule, [h]).error.messageKey, 'ruleMissing');
const nested = rule(refH, rule(refH, zero, result), app(refH, result));
assert(custom(nested, [h]).ok, 'Rules can contain rules');
assert(custom(judgment(rule(refH, zero, result), nat), [h]).ok, 'A judgment can contain a rule');
const lambdaVar = b('tt_var', {}, { REF: 'lambda-x\u241fx' });
const lambda = b('tt_lam', { BODY: rule(refH, lambdaVar, zero) });
lambda.binds = { BODY: ['lambda-x'] }; lambda.names = { 'lambda-x': 'x' };
assert(!custom(judgment(lambda, arrow), [h]).ok, 'Bad conclusions are checked inside lambda scope');
lambda.inputs.BODY.inputs.RESULT = app(refH, lambdaVar);
assert(custom(judgment(lambda, arrow), [h]).ok);
const local = b('tt_var', {}, { REF: 'root-x\u241fx' });
const l0 = problem(judgment(local, b('tt_given', {}, { IDX: '0' })));
l0.binds = { TERM: ['root-x'] }; l0.names = { 'root-x': 'x' };
assert(M.checkWorkshop(levels[0], l0, []).ok, 'Preset local scope survives its new shell');
const inferRoot = problem(judgment(zero, nat));
const inferSimple = { givens: [], inferTerm: M.ZERO };
assert(M.checkWorkshop(inferSimple, inferRoot, []).ok);
assert(!M.checkWorkshop(inferSimple, problem(judgment(zero, bool)), []).ok);
console.log('PASS: single entry, typed judgments, real holes, checked rule conclusions, nesting and preset scopes');
