'use strict';
const assert = require('assert');
const M = require('../src/core/mltt.js');
const { levels } = require('../src/levels/index.js');
const block = (type, fields = {}, inputs = {}, id = type) => ({ type, id, fields, inputs });
const symbol = id => block('tt_symbol', { REF: id }, {}, 'use-' + id);
const declaration = (id, name, kind, type, value) => block('tt_declare', { NAME: name, KIND: kind }, { TYPE: type, VALUE: value }, id);
const nat = block('tt_nat'), zero = block('tt_zero');
const answer = term => block('tt_answer', {}, { TERM: term }, 'answer');
const level = { givens: [], goal: M.NAT };
const check = (term, declarations, lv = level) => M.checkWorkshop(lv, answer(term), declarations);
const n = declaration('n', 'n', 'definition', nat, zero);
assert(check(symbol('n'), [n]).ok);
assert(M.conv(M.evalTm([], check(symbol('n'), [n]).term), M.evalTm([], M.ZERO)));
const a = declaration('a', 'a', 'axiom', nat);
assert.deepEqual(check(symbol('a'), [a]).assumptions.map(d => d.id), ['a']);
assert.deepEqual(check(zero, [a]).assumptions, []);
const nFromA = declaration('n', 'n', 'definition', nat, symbol('a'));
assert.deepEqual(check(symbol('n'), [nFromA, a]).assumptions.map(d => d.id), ['a']);
assert(!check(symbol('n'), [nFromA]).ok);
const cycleA = declaration('a', 'a', 'definition', nat, symbol('b'));
const cycleB = declaration('b', 'b', 'definition', nat, symbol('a'));
assert.equal(check(zero, [cycleA, cycleB]).error.code, 'E_DECLARATION');
assert.equal(check(zero, [n, declaration('other', 'n', 'axiom', nat)]).error.code, 'E_DECLARATION');
assert(!check(zero, [declaration('bad', 'bad', 'definition', nat, block('tt_true'))]).ok);
assert(!check(zero, [declaration('bad', 'bad', 'axiom', zero)]).ok);
assert(!check(zero, [declaration('bad', 'bad', 'definition', nat, block('tt_hole'))]).ok);
// A declared type can be used by another declaration, without touching DEFS.
const typeA = declaration('A', 'A', 'axiom', block('tt_U', { LEVEL: '0' }));
const x = declaration('x', 'x', 'assumption', symbol('A'));
const idAXX = block('tt_id', {}, { TY: symbol('A'), L: symbol('x'), R: symbol('x') });
const proof = declaration('proof', 'proof', 'definition', idAXX, block('tt_refl'));
assert(check(zero, [proof, x, typeA]).ok);
assert(!M.DEFS.has('A'));
// Declarations see the answer-slot locals, including dependent context indices.
const localAnswer = answer(symbol('copy'));
localAnswer.binds = { TERM: ['answer-x'] };
localAnswer.names = { 'answer-x': 'x' };
const copy = declaration('copy', 'copy', 'definition', block('tt_given', { IDX: '0' }), block('tt_var', { REF: 'answer-x␟x' }));
assert(M.checkWorkshop(levels[0], localAnswer, [copy]).ok);
const underLambda = block('tt_lam', {}, { BODY: symbol('copy') });
underLambda.binds = { BODY: ['inner'] }; underLambda.names = { inner: 'y' };
const localLv = { ...levels[0], goal: M.Pi('y', M.Var(1), M.Var(2)) };
assert(M.checkWorkshop(localLv, { ...localAnswer, inputs: { TERM: underLambda } }, [copy]).ok);
const renamed = { ...localAnswer, names: { 'answer-x': 'renamed' } };
assert.equal(M.checkWorkshop(levels[0], renamed, [declaration('collision', 'renamed', 'axiom', nat)]).error.code, 'E_DECLARATION');
assert.equal(M.inspectWorkshop(level, answer(zero), [n], 'n').selectedType, 'ℕ');
assert.equal(M.inspectWorkshop(level, answer(null), [], 'scratch', block('tt_suc', {}, { N: zero }, 'scratch')).selectedType, 'ℕ');
assert.equal(M.inspectWorkshop({ givens: [], goal: M.UNIT }, answer(zero), [], zero.id).selectedType, 'ℕ');
assert.equal(M.inspectWorkshop(level, answer(null), [n], 'n').selectedType, 'ℕ');
console.log('PASS: workshop definitions, computation, transitive assumptions, dependency order, scope, cycles, names, holes and inspection');
