'use strict';
const assert = require('node:assert/strict');
const M = require('../src/core/mltt.js');
const b = (type, inputs = {}, fields = {}, id = type) => ({ type, inputs, fields, id });
const problem = (type, term) => b('tt_problem', { TYPE: type, TERM: term });
const unit = b('tt_unit'), star = b('tt_star'), zero = b('tt_zero');
assert(M.checkCustomProblem(problem(unit, star), []).ok);
assert(!M.checkCustomProblem(problem(unit, zero), []).ok);
assert(!M.checkCustomProblem(problem(zero, zero), []).ok, 'The goal must be a type');
assert(!M.checkCustomProblem(problem(null, star), []).ok);
const symbol = id => b('tt_symbol', {}, { REF: id });
const declaration = (id, kind, type, value) => b('tt_declare', { TYPE: type, VALUE: value }, { NAME: id, KIND: kind }, id);
const A = declaration('A', 'assumption', b('tt_U'));
const arrow = b('tt_pi', { DOM: symbol('A'), BODY: symbol('A') });
arrow.binds = { BODY: ['pi-x'] }; arrow.names = { 'pi-x': 'x' };
const lambda = b('tt_lam', { BODY: b('tt_var', {}, { REF: 'lam-x␟x' }) });
lambda.binds = { BODY: ['lam-x'] }; lambda.names = { 'lam-x': 'x' };
const result = M.checkCustomProblem(problem(arrow, lambda), [A]);
assert(result.ok);
assert(result.assumptions.some(d => d.id === 'A'), 'Track assumptions used in the custom target');
const witness = declaration('a', 'axiom', symbol('A'));
assert(M.checkCustomProblem(problem(symbol('A'), symbol('a')), [A, witness]).ok);
const wrong = declaration('a', 'definition', symbol('A'), star);
assert(!M.checkCustomProblem(problem(symbol('A'), symbol('a')), [A, wrong]).ok);
console.log('PASS: custom target construction, missing/invalid goals, transparent contexts, dependent symbols and assumptions');
